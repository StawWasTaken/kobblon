begin;

/*
 * Everything a person writes goes past Kobby except the three pieces of
 * writing that are on every page they appear on: their handle, their
 * display name and their bio.
 *
 * The list screens those at the door - `check_username` and
 * `change_username` both ask `screen_text` - and 0254 stopped the door
 * being walked around with `f_u_c_k`. But a list is a list: it has the
 * words somebody thought of, and a handle that is a slur nobody wrote down,
 * or a bio that is an address to meet at, passes it and then sits there.
 * Chat has had Kobby reading it since 0189 and names have had nobody.
 *
 * So names and bios get the same treatment as a line of chat: a queue, a
 * judgement against the numbered rules, and the rung decided by the rule's
 * gravity and the person's bar rather than by the model. Kobby is the brain
 * of it; the list is its reflexes.
 *
 * What it may do to a name is deliberately narrow:
 *
 *   * a bio or a display name is **taken away** - the bio emptied, the
 *     display name set back to the handle - because nothing is lost by it
 *     and they can write another one;
 *   * a handle is **reset** to `player<content id>`, through the same
 *     `kobbleston.renaming` flag `change_username` uses, and they are told
 *     so and may pick a new one free. It is not taken from them quietly:
 *     renaming them to nothing is not possible and leaving a slur up while
 *     a ticket waits is the thing being fixed;
 *   * and never a deletion, by Kobby or anybody automated, ever.
 */

create table if not exists public.names_to_read (
  id bigint generated by default as identity primary key,
  who uuid not null references public.profiles(id) on delete cascade,
  kind text not null check (kind in ('username', 'display_name', 'bio')),
  body text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists names_to_read_waiting_idx
  on public.names_to_read (created_at) where read_at is null;
create index if not exists names_to_read_who_idx
  on public.names_to_read (who, created_at desc);

alter table public.names_to_read enable row level security;

/*
 * The grants, in the same file as the table, because a policy without them
 * is a table nobody can reach - twice now in this project.
 */
grant select on public.names_to_read to authenticated;
grant usage, select on sequence public.names_to_read_id_seq to authenticated;

drop policy if exists names_to_read_staff on public.names_to_read;
create policy names_to_read_staff on public.names_to_read
  for select using (public.is_moderator());

drop trigger if exists poke_on_new_name on public.names_to_read;
create trigger poke_on_new_name
  after insert on public.names_to_read
  for each row when (new.read_at is null)
  execute function public.poke_on_new_work();

/** What a person wrote about themselves, handed to the queue. */
create or replace function public.watch_profile_text()
returns trigger language plpgsql security definer
set search_path = public, extensions as $$
begin
  /*
   * Kobby's own reset is a write to `username`, and queueing it would hand
   * Kobby the name it just chose, for ever. The flag is the one
   * `change_username` already raises, and it is transaction-local.
   */
  if coalesce(current_setting('kobbleston.renaming', true), 'off') = 'on' then
    return null;
  end if;

  if coalesce(new.is_guest, false)
     or coalesce(new.is_admin, false)
     or coalesce(new.is_moderator, false)
     or coalesce(new.is_superadmin, false) then
    return null;
  end if;

  if tg_op = 'INSERT' or new.username is distinct from old.username then
    insert into public.names_to_read (who, kind, body) values (new.id, 'username', new.username);
  end if;

  if (tg_op = 'INSERT' or new.display_name is distinct from old.display_name)
     and coalesce(trim(new.display_name), '') <> ''
     and lower(trim(new.display_name)) <> lower(new.username) then
    insert into public.names_to_read (who, kind, body) values (new.id, 'display_name', new.display_name);
  end if;

  if (tg_op = 'INSERT' or new.bio is distinct from old.bio)
     and coalesce(trim(new.bio), '') <> '' then
    insert into public.names_to_read (who, kind, body) values (new.id, 'bio', new.bio);
  end if;

  return null;
end $$;

drop trigger if exists read_what_they_wrote_about_themselves on public.profiles;
create trigger read_what_they_wrote_about_themselves
  after insert or update of username, display_name, bio on public.profiles
  for each row execute function public.watch_profile_text();

/**
 * One account's writing put back in the queue, for staff who want a second
 * reading of somebody already here. Nothing is backfilled on its own: every
 * account that existed before this migration would arrive at once and the
 * minute's budget would be spent on handles nobody has complained about.
 */
create or replace function public.queue_profile_text(target uuid)
returns integer language plpgsql security definer
set search_path = public, extensions as $$
declare
  they record;
  added integer := 0;
begin
  if not public.is_moderator() then
    raise exception 'This is staff only.';
  end if;

  select * into they from public.profiles where id = target;
  if they is null then raise exception 'No such account.'; end if;

  insert into public.names_to_read (who, kind, body) values (target, 'username', they.username);
  added := 1;

  if coalesce(trim(they.display_name), '') <> ''
     and lower(trim(they.display_name)) <> lower(they.username) then
    insert into public.names_to_read (who, kind, body) values (target, 'display_name', they.display_name);
    added := added + 1;
  end if;

  if coalesce(trim(they.bio), '') <> '' then
    insert into public.names_to_read (who, kind, body) values (target, 'bio', they.bio);
    added := added + 1;
  end if;

  return added;
end $$;

grant execute on function public.queue_profile_text(uuid) to authenticated;

commit;
