begin;

/*
 * A community name is owned too.
 *
 * Staw: "for communities its the same thing, communities can have spaces,
 * they can have special characters, numbers, but they need to be unique, and
 * communities can also change names so theres previous names too, and
 * community names must be unique and checked by kobby".
 *
 * So: the same promise as 0277 makes about usernames, with a different
 * charset. A community name is a name people write, not a handle people
 * type into an address, so spaces and punctuation stay - the `slug` is the
 * thing that goes in a link and it already has its own narrow rule.
 *
 * Three things were missing, not one:
 *
 *   * `communities.name` was never unique. Two communities could be called
 *     the same thing, and on a list of them there was no way to tell which
 *     one anybody meant.
 *   * there was no history at all, so a renamed community's old name was
 *     free immediately.
 *   * `name` was directly updatable through `communities_update_own`, so
 *     any rename went around whatever checking a function might do. That is
 *     the same hole `guard_username` closed for people in 0022, and it gets
 *     the same latch: a transaction-local flag that only the rename
 *     function raises, never an identity test.
 */

-- ------------------------------------------------------------- the charset
--
-- Spaces and punctuation are allowed; control characters are not, and
-- neither is a name that is only whitespace or that leans on invisible
-- characters to look like one that is taken.

create or replace function public.community_name_shape()
returns text language sql immutable as $$ select '^[^[:cntrl:]]{3,48}$' $$;

create or replace function public.community_name_shape_said()
returns text language sql immutable as $$
  select 'A community name is 3 to 48 characters. Spaces and punctuation are fine.'
$$;

grant execute on function public.community_name_shape to anon, authenticated;
grant execute on function public.community_name_shape_said to anon, authenticated;

-- ------------------------------------------------------------- the history
--
-- Every `create table` in this project is followed by its grants in the same
-- file, because a policy without them is a table nobody can reach, and this
-- project has shipped that twice.

create table if not exists public.community_name_history (
  id bigint generated by default as identity primary key,
  community_id uuid not null references public.communities(id) on delete cascade,
  name text not null,
  changed_at timestamptz not null default now()
);

create index if not exists community_name_history_idx
  on public.community_name_history (community_id, changed_at desc);

alter table public.community_name_history enable row level security;

grant select on public.community_name_history to anon, authenticated;

drop policy if exists community_name_history_read on public.community_name_history;
create policy community_name_history_read on public.community_name_history
  for select using (true);

-- Nothing writes to it but the rename itself.
revoke insert, update, delete on public.community_name_history from anon, authenticated;

-- --------------------------------------------- names that already collide
--
-- `name` has never been unique, so duplicates may be sitting there now. The
-- oldest keeps the name, because it is the one everybody else's was a
-- duplicate of; the rest get their content id put on the end, which is
-- ugly, visible and fixable by their owner, where a failed migration is
-- none of those things.

update public.communities c
   set name = left(c.name, 40) || ' ' || coalesce(c.content_id::text, left(c.id::text, 6))
 where not c.is_removed
   and exists (
   select 1 from public.communities older
    where lower(older.name) = lower(c.name)
      and not older.is_removed
      and (older.created_at, older.id) < (c.created_at, c.id)
 );

-- Partial, and deliberately so: `who_holds_community_name` treats a removed
-- community's current name as free, and an index that still held it would
-- make the two disagree - the check would say yes and the insert would then
-- fail on a constraint, which is the worst of both.
create unique index if not exists communities_one_name_idx
  on public.communities (lower(name)) where not is_removed;

-- ------------------------------------------------------------ who holds one

create or replace function public.who_holds_community_name(candidate text)
returns uuid language sql stable security definer set search_path = public, extensions as $$
  select id from public.communities
   where lower(name) = lower(trim(candidate)) and not is_removed
  union all
  select community_id from public.community_name_history
   where lower(name) = lower(trim(candidate))
  limit 1;
$$;

grant execute on function public.who_holds_community_name to anon, authenticated;

-- ----------------------------------------------------------------- the door
--
-- What the create form and the rename form both ask while somebody types.
-- Kobby is the `screen_text` call: the name is judged before the community
-- exists, the same as a username is.
--
-- `for_community` is the community being renamed, so its own current name
-- does not come back as taken when somebody edits a word in the middle of
-- it and puts it back.

create or replace function public.check_community_name(candidate text, for_community uuid default null)
returns table (ok boolean, reason text)
language plpgsql stable security definer set search_path = public, extensions as $$
declare
  verdict record;
  holder uuid;
begin
  candidate := trim(coalesce(candidate, ''));

  if candidate !~ public.community_name_shape() then
    return query select false, public.community_name_shape_said();
    return;
  end if;

  holder := public.who_holds_community_name(candidate);
  if holder is not null and holder is distinct from for_community then
    return query select false, 'A community already has that name.';
    return;
  end if;

  select * into verdict from public.screen_text(candidate, 'identity');
  if verdict.decision <> 'ok' then
    return query select false, coalesce(verdict.reason, 'That name is not allowed.');
    return;
  end if;

  return query select true, null::text;
end;
$$;

grant execute on function public.check_community_name to anon, authenticated;

-- ------------------------------------------------------------- the latch
--
-- `communities_update_own` lets an owner update the row, which included the
-- name. The guard pins the name back unless the rename function raised the
-- flag.
--
-- Its subject is the flag and nothing else. A guard whose subject is
-- identity is the third trap in this project's notes: `security definer`
-- changes a function's rights, not who it reports as, so a guard asking
-- `auth.uid()` undoes a privileged write and returns success while the row
-- does not move.

create or replace function public.guard_community_name()
returns trigger language plpgsql security definer
set search_path = public, extensions as $$
begin
  if new.name is distinct from old.name
     and coalesce(current_setting('kobbleston.renaming_community', true), 'off') <> 'on' then
    new.name := old.name;
  end if;
  return new;
end;
$$;

drop trigger if exists guard_community_name on public.communities;
create trigger guard_community_name before update on public.communities
  for each row execute function public.guard_community_name();

-- ---------------------------------------------------------------- renaming
--
-- The owner or an admin of the community. Free, unlike a username: a
-- community is a thing a group runs together and charging one person's
-- Brix for a decision the group made is the wrong shape.

create or replace function public.rename_community(target uuid, new_name text)
returns text language plpgsql security definer
set search_path = public, extensions as $$
declare
  me uuid := auth.uid();
  current_name text;
  holder uuid;
  verdict record;
  coming_back boolean;
  my_role public.community_role;
  landed text;
begin
  if me is null then raise exception 'Sign in first.'; end if;
  if public.is_guest() then raise exception 'Guests cannot rename a community.'; end if;

  new_name := trim(coalesce(new_name, ''));

  select name into current_name from public.communities
   where id = target and not is_removed;
  if not found then raise exception 'That community is not here.'; end if;

  select role into my_role from public.community_members
   where community_id = target and user_id = me;
  if not found or my_role not in ('owner', 'admin') then
    raise exception 'Only the owner or an admin may rename a community.';
  end if;

  if lower(new_name) = lower(current_name) then
    raise exception 'That is already its name.';
  end if;

  if new_name !~ public.community_name_shape() then
    raise exception '%', public.community_name_shape_said();
  end if;

  holder := public.who_holds_community_name(new_name);
  coming_back := holder = target;

  if holder is not null and not coming_back then
    raise exception 'A community already has that name.';
  end if;

  -- A name this community already had has been past Kobby once. Same
  -- reasoning as a username coming back in 0277.
  if not coming_back then
    select * into verdict from public.screen_text(new_name, 'identity');
    if verdict.decision <> 'ok' then
      raise exception 'That name is not allowed here.';
    end if;
  end if;

  if coming_back then
    delete from public.community_name_history
     where community_id = target and lower(name) = lower(new_name);
  end if;

  insert into public.community_name_history (community_id, name) values (target, current_name);

  perform set_config('kobbleston.renaming_community', 'on', true);
  update public.communities set name = new_name where id = target;
  perform set_config('kobbleston.renaming_community', 'off', true);

  -- Read it back rather than trust the update, for the reason in 0277.
  select name into landed from public.communities where id = target;
  if landed is distinct from new_name then
    raise exception 'The rename did not hold.';
  end if;

  return new_name;
end;
$$;

grant execute on function public.rename_community to authenticated;

-- ------------------------------------------------- the names it used to have

create or replace function public.community_name_history_of(target uuid)
returns table (name text, changed_at timestamptz)
language sql stable security definer set search_path = public, extensions as $$
  select h.name, h.changed_at
    from public.community_name_history h
   where h.community_id = target
   order by h.changed_at desc
   limit 20;
$$;

grant execute on function public.community_name_history_of to anon, authenticated;

-- -------------------------------------------------- making one, named properly
--
-- Taken from 0015 as it stands, with the name check added at the top and
-- nothing else touched. Without it the unique index above turns a taken
-- name into a constraint violation on insert, which reaches somebody as
-- "duplicate key value violates unique constraint" after they have filled
-- in a whole form.
--
-- `name` is trimmed on the way in, because the index is on `lower(name)`
-- and nothing else: "Builders" and "Builders " are two rows to Postgres and
-- one name to everybody looking at them.

create or replace function public.create_community(
  name text,
  slug text,
  description text default null,
  icon_url text default null,
  banner_url text default null,
  join_policy text default 'open'
)
returns uuid language plpgsql security definer set search_path = public, extensions as $$
declare
  me uuid := auth.uid();
  cost constant integer := 100;
  balance integer;
  community uuid;
  owner_rank uuid;
  verdict record;
begin
  if me is null then raise exception 'not signed in'; end if;
  if public.is_guest() then raise exception 'Guests cannot make a Community.'; end if;

  name := trim(coalesce(name, ''));

  select * into verdict from public.check_community_name(name, null);
  if not verdict.ok then
    raise exception '%', verdict.reason;
  end if;

  select pixels into balance from public.profiles where id = me;
  if balance < cost then
    raise exception 'Making a Community costs % Brix. You have %.', cost, balance;
  end if;

  insert into public.communities (owner_id, slug, name, description, icon_url, banner_url, join_policy)
  values (me, slug, name, nullif(trim(description), ''), icon_url, banner_url, join_policy)
  returning id into community;

  -- Two ranks to begin with: the one that runs it and the one everyone else
  -- lands on.
  insert into public.community_ranks
    (community_id, rank, name, can_post_wall, can_moderate_wall,
     can_manage_members, can_manage_ranks, can_manage_community, can_manage_spaces)
  values (community, 254, 'Owner', true, true, true, true, true, true)
  returning id into owner_rank;

  insert into public.community_ranks (community_id, rank, name)
  values (community, 1, 'Member');

  update public.community_members
     set role = 'owner', rank_id = owner_rank
   where community_id = community and user_id = me;

  perform public.move_pixels(me, -cost, 'purchase', 'Created the Community ' || name);
  perform public.log_community(community, 'created', name);

  return community;
end;
$$;

grant execute on function public.create_community to authenticated;

commit;
