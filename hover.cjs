const { chromium } = require('playwright')
;(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] })
  const c = await b.newContext({ viewport: { width: 900, height: 420 }, deviceScaleFactor: 2 })
  const page = await c.newPage()
  await page.route('**/*', r => r.request().url().includes('supabase') ? r.fulfill({ status: 200, body: '[]' }) : r.continue())
  await page.goto('http://localhost:5398/style', { waitUntil: 'networkidle' })
  const row = page.locator('#controls').locator('div.flex.flex-wrap').first()
  await row.scrollIntoViewIfNeeded(); await page.waitForTimeout(400)
  await row.screenshot({ path: '/tmp/claude-0/btn-rest.png' })
  await page.locator('#controls').getByRole('button', { name: 'Yes' }).hover(); await page.waitForTimeout(400)
  await row.screenshot({ path: '/tmp/claude-0/btn-hover-green.png' })
  await page.locator('#controls').getByRole('button', { name: 'Primary' }).hover(); await page.waitForTimeout(400)
  await row.screenshot({ path: '/tmp/claude-0/btn-hover-blue.png' })
  await b.close()
})()
